import Foundation

/// 写真を大きく見る画面（`PhotoViewerView`）の**上下の情報を隠すか**（2026-11-12 owner の要望・画面写真つき）。
///
/// 「タップすると下の情報が消えて、写真だけ見られるようにしたい。もう一度タップするとまた表示される」。
/// 隠すのは ✕・「1 / 41」・共有・サムネイルの帯・題・撮影地・機材と撮影設定・ハート（上の列と下の重ね）。
///
/// 2026-11-12 判断（決まりはここに1つだけ置き、画面はこれを読むだけにする）:
///
/// 1. **1回押すと隠す・もう1回で出す。** 2回押す（いいね・拡大を戻す）は別の身振りで、
///    1回押しは2回押しが成り立たなかったときだけ届く（画面で `onTapGesture(count: 2)` を先に付ける）。
///    なので2回押しで隠れたり出たりはしない
/// 2. **隠したまま左右に送っても隠したまま**（iPhone の「写真」と同じ）。送りでは何も変えない
/// 3. **拡大中に1回押しても、倍率はそのまま隠す・出すだけ**（「写真」と同じ。拡大を戻すのは2回押し）
/// 4. **VoiceOver が動いている間は隠さない**——読み上げで題・撮影情報が読めて、✕ で閉じられるように。
///    途中で VoiceOver を点けたときも、隠していた分をすぐ出す
/// 5. 隠している間の戻り方は「もう1回押す」（✕ が出る）。下へ引いて閉じる操作はこの画面に無い
///    （ページ式の送り・拡大中の移動と身振りがぶつかるので、今回は足さない）。
///    VoiceOver の「戻る」（2本指で Z）でも閉じられる（画面の `accessibilityAction(.escape)`）
/// 6. 切り替えは短くふわっと（0.2 秒の濃さ＋少しの寄り）。「視差効果を減らす」がオンなら寄りを無くし、濃さだけ。
///    状態バーはこの画面では前から隠している（`statusBarHidden`）ので、ここでは触らない
struct ViewerChrome: Equatable {

    /// 利用者が1回押して隠したか
    private(set) var isHidden = false

    /// 1回押した。**VoiceOver が動いている間は何もしない**（隠さない・4）
    mutating func singleTap(voiceOver: Bool) {
        guard !voiceOver else { return }
        isHidden.toggle()
    }

    /// 上下の情報を出すか
    func shows(voiceOver: Bool) -> Bool {
        voiceOver || !isHidden
    }

    /// 消える・出るのにかける秒（短く・ふわっと）
    static let fadeDuration: Double = 0.2

    /// 消えるときに、端の方へ寄る量（pt）。「視差効果を減らす」がオンなら寄らない（濃さだけ）
    static func slide(reduceMotion: Bool) -> Double {
        reduceMotion ? 0 : 12
    }
}
