    /// 質問に合う頁（当たった言葉の多い順に2つまで）
    static func matching(_ question: String) -> [AskHelpPage] {
        let text = SearchSentence.fold(question).lowercased()
        let scored = all.map { page -> (AskHelpPage, Int) in
            let words = page.keywords + [page.title]
            return (page, words.filter { text.contains(SearchSentence.fold($0).lowercased()) }.count)
        }
        return scored.filter { $0.1 > 0 }.sorted { $0.1 > $1.1 }.prefix(2).map(\.0)
    }

    /// AI に渡す行（頁の題と3行）
    static func lines(_ pages: [AskHelpPage]) -> String {
        guard !pages.isEmpty else { return L("合う使い方の頁はありませんでした。", "No matching help page.") }
        return pages.map { p in "【\(p.title)】\n" + p.lines.joined(separator: "\n") }.joined(separator: "\n\n")
    }
